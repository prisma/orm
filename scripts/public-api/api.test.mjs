import { deepStrictEqual, match, strictEqual, throws } from 'node:assert/strict';
import { existsSync, readFileSync, rmSync } from 'node:fs';
import { basename, dirname, join } from 'node:path';
import { describe, it } from 'node:test';
import { fileURLToPath } from 'node:url';
import { apiText, main, publishedPackageDirs, workerStopped } from './api.mjs';
import { augmentsItself, entryPointsOf, readPackageApi } from './read-api.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const fixtures = join(here, 'fixtures');

describe('apiText', () => {
  it('puts a header above the lines and ends with a newline', () => {
    strictEqual(
      apiText(['.: const a: 1', '.: const b: 2']),
      '# Generated by `pnpm api:update` from the built declarations. Do not edit by hand.\n.: const a: 1\n.: const b: 2\n',
    );
  });
});

describe('publishedPackageDirs', () => {
  it('lists the package folders, and apart from them folders that hold only an api.txt', () => {
    const { packageDirs, leftovers } = publishedPackageDirs(join(fixtures, 'root-leftover'));
    deepStrictEqual(
      packageDirs.map((dir) => basename(dir)),
      ['clean'],
    );
    deepStrictEqual(
      leftovers.map((dir) => basename(dir)),
      ['leftover'],
    );
  });
});

function output() {
  let text = '';
  return { write: (chunk) => (text += chunk), text: () => text };
}

describe('main', () => {
  it('passes check when every list matches', async () => {
    const stdout = output();
    strictEqual(await main({ mode: 'check', root: join(fixtures, 'root-clean'), stdout }), 0);
    strictEqual(stdout.text(), 'api:check: all 1 lists match the build\n');
  });

  it('fails check, naming a stale and a missing list and how to fix them', async () => {
    const stderr = output();
    strictEqual(await main({ mode: 'check', root: join(fixtures, 'root-stale'), stderr }), 1);
    strictEqual(
      stderr.text(),
      [
        'api:check: these API lists do not match the build:',
        '',
        'packages/9-public/@prisma/missing/api.txt',
        '  + .: function absent(): void',
        '',
        'packages/9-public/@prisma/stale/api.txt',
        '  - .: function ready(value: string): void',
        '  + .: function ready(): void',
        '',
        'Run `pnpm build`, then `pnpm api:update`, and commit the changed api.txt files. Do not edit or hand-merge an api.txt.',
        'The lists this run generated are in each package\'s dist-api/api.txt; in CI they are uploaded as the workflow artifact "api-lists", which can be downloaded from the run.',
        '',
      ].join('\n'),
    );
  });

  it('writes the lists it generated in check mode where CI can upload them', async () => {
    const stderr = output();
    await main({ mode: 'check', root: join(fixtures, 'root-stale'), stderr });
    strictEqual(
      readFileSync(
        join(fixtures, 'root-stale/packages/9-public/@prisma/stale/dist-api/api.txt'),
        'utf8',
      ),
      apiText(['.: function ready(): void']),
    );
  });

  it('names the package folder of a package.json it cannot read or that has no exports', async () => {
    const stderr = output();
    strictEqual(await main({ mode: 'check', root: join(fixtures, 'root-broken'), stderr }), 1);
    match(stderr.text(), /packages\/9-public\/@prisma\/malformed: cannot read package\.json: /);
    match(
      stderr.text(),
      /packages\/9-public\/@prisma\/noexports: package\.json has no exports\. Run `pnpm build`, which writes them\./,
    );
  });

  it('writes the lists that did generate when another package fails, and no committed list', async () => {
    const okList = join(fixtures, 'root-broken/packages/9-public/@prisma/ok/dist-api/api.txt');
    rmSync(okList, { force: true });
    await main({ mode: 'check', root: join(fixtures, 'root-broken'), stderr: output() });
    strictEqual(readFileSync(okList, 'utf8'), apiText(['.: function fine(): void']));
    strictEqual(
      existsSync(join(fixtures, 'root-broken/packages/9-public/@prisma/ok/api.txt')),
      false,
    );
  });

  it('fails on a folder that has an api.txt but no package.json', async () => {
    const stderr = output();
    strictEqual(await main({ mode: 'check', root: join(fixtures, 'root-leftover'), stderr }), 1);
    match(
      stderr.text(),
      /packages\/9-public\/@prisma\/leftover has an api\.txt but no package\.json/,
    );
  });

  it('rejects an unknown mode', async () => {
    const stderr = output();
    strictEqual(await main({ mode: 'write', root: join(fixtures, 'root-clean'), stderr }), 2);
  });
});

describe('workerStopped', () => {
  it('names the package and the exit code or signal', () => {
    strictEqual(
      workerStopped('/repo/packages/9-public/@prisma/a', '/repo', 1, null).message,
      'packages/9-public/@prisma/a: the worker stopped with exit code 1 before it reported',
    );
    strictEqual(
      workerStopped('/repo/packages/9-public/@prisma/a', '/repo', null, 'SIGKILL').message,
      'packages/9-public/@prisma/a: the worker stopped on signal SIGKILL before it reported',
    );
  });
});

describe('entryPointsOf', () => {
  it('fails on a package whose exports name no import path but ./package.json', () => {
    throws(
      () => entryPointsOf(join(fixtures, 'no-entry')),
      /fixtures\/no-entry: package\.json exports no import path other than \.\/package\.json/,
    );
  });
});

describe('augmentsItself', () => {
  it('finds a declare module of the package itself, indented or not', () => {
    const packageDir = join(fixtures, 'indented-augment');
    strictEqual(augmentsItself(packageDir, entryPointsOf(packageDir)), true);
    const plain = join(fixtures, 'kinds');
    strictEqual(augmentsItself(plain, entryPointsOf(plain)), false);
  });
});

describe('readPackageApi', () => {
  it('tells the reader to build first when a declaration file is missing', () => {
    throws(
      () => readPackageApi(join(here, 'fixtures', 'unbuilt')),
      /lib\/index\.d\.mts\. Run `pnpm build` first\./,
    );
  });
});
