#!/usr/bin/env node
// Usage: node scripts/public-api/api.mjs update|check
// update: writes api.txt beside the package.json of every published package.
// check: regenerates the lists and fails when a committed api.txt differs.
// Both read the built declarations, so `pnpm build` must have run.

import { fork } from 'node:child_process';
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { availableParallelism } from 'node:os';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { compareCodeUnits } from './flatten.mjs';
import { entryPointsOf } from './read-api.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(here, '..', '..');
export const LIST_FILE = 'api.txt';
const HEADER = '# Generated by `pnpm api:update` from the built declarations. Do not edit by hand.';

export function publishedPackageDirs(root) {
  const scope = join(root, 'packages', '9-public', '@prisma');
  return readdirSync(scope)
    .filter((name) => existsSync(join(scope, name, 'package.json')))
    .sort(compareCodeUnits)
    .map((name) => join(scope, name));
}

export function apiText(lines) {
  return `${[HEADER, ...lines].join('\n')}\n`;
}

const listLines = (text) => text.split('\n').filter((line) => line !== '' && !line.startsWith('#'));

// Lines only in `generated` are added, lines only in `committed` removed. Up to `limit` of each.
export function listDifferences(committed, generated, limit = 10) {
  const before = new Set(listLines(committed));
  const after = new Set(listLines(generated));
  const added = [...after].filter((line) => !before.has(line));
  const removed = [...before].filter((line) => !after.has(line));
  const shown = [
    ...removed.slice(0, limit).map((line) => `- ${line}`),
    ...added.slice(0, limit).map((line) => `+ ${line}`),
  ];
  const hidden = Math.max(0, removed.length - limit) + Math.max(0, added.length - limit);
  if (hidden > 0) shown.push(`  ... and ${hidden} more`);
  if (shown.length === 0 && committed !== generated)
    shown.push('  (same lines, different order or spacing)');
  return shown;
}

function generateOne(packageDir) {
  return new Promise((resolveText, reject) => {
    const child = fork(join(here, 'worker.mjs'), [packageDir], {
      stdio: ['ignore', 'inherit', 'inherit', 'ipc'],
    });
    let reply;
    child.on('message', (message) => {
      reply = message;
    });
    child.on('error', reject);
    child.on('exit', (code) => {
      if (reply?.lines) resolveText(apiText(reply.lines));
      else reject(new Error(reply?.error ?? `${packageDir}: the worker exited with code ${code}`));
    });
  });
}

export async function generateLists(packageDirs, workers = Math.min(4, availableParallelism())) {
  const queue = [...packageDirs].sort(
    (a, b) => entryPointsOf(b).length - entryPointsOf(a).length || compareCodeUnits(a, b),
  );
  const texts = new Map();
  const failures = [];
  const run = async () => {
    for (let packageDir = queue.shift(); packageDir; packageDir = queue.shift()) {
      try {
        texts.set(packageDir, await generateOne(packageDir));
      } catch (error) {
        failures.push(error.message);
      }
    }
  };
  await Promise.all(Array.from({ length: workers }, run));
  return { texts, failures };
}

async function main(mode) {
  if (mode !== 'update' && mode !== 'check') {
    process.stderr.write('Usage: node scripts/public-api/api.mjs update|check\n');
    return 2;
  }
  const { texts, failures } = await generateLists(publishedPackageDirs(repoRoot));
  if (failures.length > 0) {
    process.stderr.write(
      `api:${mode}: could not list the API of every package:\n\n${failures.join('\n\n')}\n`,
    );
    return 1;
  }

  const stale = [];
  for (const [packageDir, text] of [...texts].sort(([a], [b]) => compareCodeUnits(a, b))) {
    const file = join(packageDir, LIST_FILE);
    const committed = existsSync(file) ? readFileSync(file, 'utf8') : '';
    if (committed === text) continue;
    stale.push({ file: relative(repoRoot, file), differences: listDifferences(committed, text) });
    if (mode === 'update') writeFileSync(file, text);
  }

  if (mode === 'update') {
    process.stdout.write(`api:update: ${stale.length} of ${texts.size} lists changed\n`);
    for (const { file } of stale) process.stdout.write(`  ${file}\n`);
    return 0;
  }
  if (stale.length === 0) {
    process.stdout.write(`api:check: all ${texts.size} lists match the build\n`);
    return 0;
  }
  process.stderr.write('api:check: these API lists do not match the build:\n');
  for (const { file, differences } of stale) {
    process.stderr.write(`\n${file}\n${differences.map((line) => `  ${line}`).join('\n')}\n`);
  }
  process.stderr.write(
    '\nRun `pnpm build`, then `pnpm api:update`, and commit the changed api.txt files. Do not edit or hand-merge an api.txt.\n',
  );
  return 1;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  process.exitCode = await main(process.argv[2]);
}
