import { mkdtemp, readFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createDevDatabase, timeouts, withClient } from '@repo/test-utils';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';
import { runDbInit } from './fixtures/example-app/db-init';
import { setUpSupabaseMockSchema } from './fixtures/supabase-reference/set-up-mock-schema';

describe('Profile.id in the example app', () => {
  let database: Awaited<ReturnType<typeof createDevDatabase>>;
  let migrationsDir: string;

  beforeEach(async () => {
    database = await createDevDatabase();
    migrationsDir = await mkdtemp(join(tmpdir(), 'supabase-profile-id-'));
  }, timeouts.spinUpPpgDev);

  afterEach(async () => {
    if (database) await database.close();
    if (migrationsDir) await rm(migrationsDir, { recursive: true, force: true });
  }, timeouts.spinUpPpgDev);

  it('the fixture schema is the schema examples/supabase ships', async () => {
    const [fixture, example] = await Promise.all([
      readFile(new URL('./fixtures/example-app/contract.prisma', import.meta.url), 'utf8'),
      readFile(
        new URL('../../../../examples/supabase/src/contract.prisma', import.meta.url),
        'utf8',
      ),
    ]);
    expect(fixture).toBe(example);
  });

  it(
    'is generated by the database for an insert that does not go through the Prisma client',
    async () => {
      const { connectionString } = database;
      await withClient(connectionString, async (pg) => {
        await setUpSupabaseMockSchema(pg);
      });
      await runDbInit(connectionString, migrationsDir);

      const userId = crypto.randomUUID();
      const inserted = await withClient(connectionString, async (pg) => {
        await pg.query(
          'INSERT INTO auth.users (id, email, created_at, updated_at) VALUES ($1, $2, now(), now())',
          [userId, `${userId}@example.com`],
        );
        const result = await pg.query<{ id: string }>(
          'INSERT INTO public.profile (username, "userId") VALUES ($1, $2) RETURNING id',
          ['alice', userId],
        );
        return result.rows;
      });

      expect(inserted).toEqual([
        {
          id: expect.stringMatching(
            /^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[0-9a-f]{4}-[0-9a-f]{12}$/,
          ),
        },
      ]);
    },
    timeouts.spinUpPpgDev * 2,
  );
});
